const uint16_t* characterRows(uint8_t family) {
  switch (family % kCharacterVisualFamilyCount) {
    case 0:
      return kCharacterBaby;
    case 1:
      return kCharacterSprout;
    case 2:
      return kCharacterBuddy;
    case 3:
      return kCharacterMame;
    case 4:
      return kCharacterDream;
    case 5:
      return kCharacterAthlete;
    case 6:
      return kCharacterRascal;
    case 7:
      return kCharacterScholar;
    case 8:
      return kCharacterElder;
    default:
      return kCharacterBaby;
  }
}

uint16_t readCharacterFamilyRow(const uint16_t* rows, uint8_t row) {
  return pgm_read_word(rows + row);
}

uint16_t readCharacterCatalogRow(uint8_t catalogId, uint8_t row) {
  if (catalogId >= kCharacterVisualCatalogCount) {
    catalogId = 0;
  }
  return pgm_read_word(&kCharacterCatalogBitmaps[catalogId][row]);
}

uint32_t readCharacterIdleRow(uint8_t catalogId, uint8_t row) {
  if (catalogId >= kCharacterVisualCatalogCount) {
    catalogId = 0;
  }
  return pgm_read_dword(&kCharacterIdleBitmaps[catalogId][row]);
}

void drawCharacterRows(EchoPetDisplayDevice& display, int16_t x, int16_t y,
                       const uint16_t* familyRows, uint8_t catalogId,
                       bool catalogRows, uint8_t phase, uint8_t scale) {
  if (scale == 0) scale = 1;
  const int16_t footShift = (phase & 0x01) ? scale : 0;
  for (uint8_t row = 0; row < kCharacterVisualSide; ++row) {
    const uint16_t bits =
        catalogRows ? readCharacterCatalogRow(catalogId, row)
                    : readCharacterFamilyRow(familyRows, row);
    for (uint8_t col = 0; col < kCharacterVisualSide; ++col) {
      if ((bits & (0x8000U >> col)) == 0) {
        continue;
      }
      int16_t py = y + static_cast<int16_t>(row) * scale;
      if (row >= 11 && ((col < 6) != ((phase & 0x01) == 0))) {
        py += footShift;
      }
      const int16_t px = x + static_cast<int16_t>(col) * scale;
      if (scale == 1) {
        display.drawPixel(px, py, EPD_BLACK);
      } else {
        display.fillRect(px, py, scale, scale, EPD_BLACK);
      }
    }
  }
}

void drawCharacterIdleRows(EchoPetDisplayDevice& display, int16_t x, int16_t y,
                           uint8_t catalogId, uint8_t scale) {
  if (scale == 0) scale = 1;
  for (uint8_t row = 0; row < kCharacterIdleVisualSide; ++row) {
    const uint32_t bits = readCharacterIdleRow(catalogId, row);
    for (uint8_t col = 0; col < kCharacterIdleVisualSide; ++col) {
      if ((bits & (0x800000UL >> col)) == 0) {
        continue;
      }
      const int16_t px = x + static_cast<int16_t>(col) * scale;
      const int16_t py = y + static_cast<int16_t>(row) * scale;
      if (scale == 1) {
        display.drawPixel(px, py, EPD_BLACK);
      } else {
        display.fillRect(px, py, scale, scale, EPD_BLACK);
      }
    }
  }
}

