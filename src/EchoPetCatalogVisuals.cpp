void drawRows(EchoPetDisplayDevice& display, const uint16_t* rows, int16_t x,
              int16_t y, uint8_t scale) {
  if (scale == 0) scale = 1;
  for (uint8_t row = 0; row < kCatalogVisualSide; ++row) {
    const uint16_t bits = pgm_read_word(rows + row);
    for (uint8_t col = 0; col < kCatalogVisualSide; ++col) {
      if ((bits & (0x8000U >> col)) == 0) {
        continue;
      }
      const int16_t px = x + static_cast<int16_t>(col) * scale;
      const int16_t py = y + static_cast<int16_t>(row) * scale;
      if (scale == 1) {
        display.drawPixel(px, py, EPD_BLACK);
      } else {
        display.fillRect(px, py, scale, scale, EPD_BLACK);
      }
    }
  }
}

uint16_t readSouvenirMemoryRow(uint8_t index, uint8_t row) {
  if (index >= kCatalogSouvenirMemoryVisualCount) {
    index = 0;
  }
  return pgm_read_word(&kSouvenirMemoryBitmaps[index][row]);
}

